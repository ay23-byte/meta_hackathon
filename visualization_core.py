"""General-purpose charts for arbitrary numeric columns.

Charts are built from the caller's selected columns, never from hardcoded
voltage/current names. Each chart carries explicit warnings about anything
that could mislead (dual axes, unsorted lines, means without uncertainty,
small groups, heuristic bins). No uncertainties are ever invented.
"""

from __future__ import annotations

import io
from dataclasses import dataclass, field

import altair as alt
import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from data_io import coerce_numeric

PLOT_SCATTER = "scatter"
PLOT_LINE = "line"
PLOT_HISTOGRAM = "histogram"
PLOT_BOX = "box"
PLOT_HEATMAP = "correlation_heatmap"
PLOT_TIME_SERIES = "time_series"
PLOT_GROUPED_BAR = "grouped_bar"
PLOT_RESIDUALS = "residuals"
PLOT_DISTRIBUTION = "distribution"
PLOT_ERRORBAR = "errorbar"

PLOT_TYPES = {
    PLOT_SCATTER: "Scatter (X vs Y)",
    PLOT_LINE: "Line / connected points",
    PLOT_HISTOGRAM: "Histogram",
    PLOT_BOX: "Box plot by group",
    PLOT_HEATMAP: "Correlation heatmap",
    PLOT_TIME_SERIES: "Time series",
    PLOT_GROUPED_BAR: "Grouped comparison (mean)",
    PLOT_RESIDUALS: "Residual plot (requires a fit)",
    PLOT_DISTRIBUTION: "Distribution / density",
    PLOT_ERRORBAR: "Points with error bars",
}

MAX_CHART_ROWS = 50_000


@dataclass
class ChartSpec:
    plot_type: str
    label: str
    chart: alt.Chart | None
    frame: pd.DataFrame
    columns: list[str]
    n_rows: int = 0
    warnings: list[str] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)

    @property
    def valid(self) -> bool:
        return self.chart is not None and self.n_rows > 0

    @property
    def reason(self) -> str:
        if self.chart is None:
            return self.warnings[0] if self.warnings else "This chart could not be built."
        if self.n_rows == 0:
            return "No complete finite rows are available for the selected columns."
        return ""

    def to_html(self, *, title: str | None = None) -> str:
        """Standalone HTML (loads Vega-Lite from a CDN at view time)."""
        if self.chart is None:
            raise ValueError(self.reason)
        heading = title or self.label
        warning_html = ""
        if self.warnings or self.notes:
            items = "".join(
                f"<li>{_escape(item)}</li>" for item in [*self.warnings, *self.notes]
            )
            warning_html = f"<ul>{items}</ul>"
        column_line = (
            f"<p><strong>Source columns:</strong> {_escape(', '.join(map(str, self.columns)))}</p>"
            if self.columns else ""
        )
        return (
            "<!DOCTYPE html><html><head><meta charset='utf-8'>"
            f"<title>{_escape(heading)}</title></head><body>"
            f"<h2>{_escape(heading)}</h2>{column_line}{warning_html}"
            + self.chart.to_html()
            + "<p style='font-size:small;color:#555'>Generated by LabLens AI. "
              "Interactive rendering requires an internet connection to load "
              "Vega-Lite from jsDelivr.</p></body></html>"
        )


def _escape(text) -> str:
    import html
    return html.escape(str(text))


def _numeric_frame(frame: pd.DataFrame, columns: list[str]) -> pd.DataFrame:
    data = {}
    for column in columns:
        if column not in frame.columns:
            continue
        data[column] = coerce_numeric(frame[column]).values
    return pd.DataFrame(data)


def _finite_pairs(frame: pd.DataFrame, columns: list[str]) -> pd.DataFrame:
    clean = _numeric_frame(frame, columns)
    if clean.empty:
        return clean
    return clean.replace([np.inf, -np.inf], np.nan).dropna().head(MAX_CHART_ROWS)


def _tooltip(columns: list[str]) -> list:
    return [alt.Tooltip(f"{name}:Q", title=name) for name in columns]


def _base_chart(plot_type: str, frame: pd.DataFrame, columns: list[str]) -> ChartSpec | None:
    if plot_type not in PLOT_TYPES:
        return ChartSpec(plot_type, plot_type, None, frame, columns,
                         warnings=[f"Unknown plot type '{plot_type}'."])
    missing = [column for column in columns if column not in frame.columns]
    if missing:
        return ChartSpec(plot_type, PLOT_TYPES[plot_type], None, frame, columns,
                         warnings=[f"Missing column(s): {', '.join(missing)}."])
    return None


def _axis_label(name, unit):
    """Use only caller-provided units; never infer them from a header."""
    return f"{name} ({unit})" if name and unit else (name or "")


def build_chart(plot_type: str, frame: pd.DataFrame, config: dict) -> ChartSpec:
    """Build one Altair chart from the caller's selected columns and options.

    Column labels are mapped to short internal field names (``x``, ``y``,
    ``group`` ...) so that arbitrary user headers containing spaces, units or
    punctuation cannot break the Vega-Lite field parser.
    """
    x_col = config.get("x")
    y_col = config.get("y")
    group_col = config.get("group")
    time_col = config.get("time")
    unc_col = config.get("uncertainty")
    secondary_cols = [column for column in config.get("secondary_y", []) if column]
    bins = min(max(int(config.get("bins", 30) or 30), 5), 100)
    fit_result = config.get("fit_result")
    numeric_columns = [c for c in (config.get("numeric_columns") or []) if c]
    x_label = _axis_label(x_col, config.get("unit_x"))
    y_label = _axis_label(y_col, config.get("unit_y"))

    def spec(chart, data: pd.DataFrame, used: list[str], *, warnings=None, notes=None) -> ChartSpec:
        return ChartSpec(
            plot_type, PLOT_TYPES.get(plot_type, plot_type), chart, data, used,
            n_rows=len(data), warnings=list(warnings or []), notes=list(notes or []),
        )

    if plot_type not in PLOT_TYPES:
        return spec(None, frame, [], warnings=[f"Unknown plot type '{plot_type}'."])

    # ---- Residuals come from the fit, not from the original frame ----
    if plot_type == PLOT_RESIDUALS:
        if fit_result is None or not getattr(fit_result, "success", False):
            return spec(None, pd.DataFrame(), [], warnings=["Fit a model before plotting residuals."])
        residual_frame = pd.DataFrame({
            "x": np.asarray(fit_result.x_fit, dtype=float),
            "residual": np.asarray(fit_result.residuals, dtype=float),
        }).replace([np.inf, -np.inf], np.nan).dropna()
        if residual_frame.empty:
            return spec(None, residual_frame, [], warnings=["The fit produced no finite residuals."])
        points = alt.Chart(residual_frame).mark_circle(size=55, opacity=0.8).encode(
            x=alt.X("x:Q", title=x_col or "X"),
            y=alt.Y("residual:Q", title="Residual (observed - fitted)"),
            tooltip=[alt.Tooltip("x:Q", title=x_col or "X"),
                     alt.Tooltip("residual:Q", format=".6g")],
        )
        zero = alt.Chart(pd.DataFrame({"y": [0.0]})).mark_rule(
            color="#b22222", strokeDash=[5, 4]
        ).encode(y="y:Q")
        return spec(
            (points + zero).properties(width="container", height=360), residual_frame,
            [x_col or "X"],
            notes=["Random scatter around zero supports the chosen model; visible structure indicates lack of fit."],
            warnings=[f"{fit_result.n_excluded} row(s) were excluded from the fit."]
            if fit_result.n_excluded else [],
        )

    # ---- Correlation heatmap uses all selected numeric columns ----
    if plot_type == PLOT_HEATMAP:
        from statistics_core import correlation_matrix
        columns = list(dict.fromkeys(
            [c for c in (numeric_columns or [x_col, y_col]) if c and c in frame.columns]
        ))
        if len(columns) < 2:
            return spec(None, frame, columns, warnings=["Select at least two numeric columns for a heatmap."])
        matrix = correlation_matrix(frame, columns, method=config.get("correlation_method", "pearson"))
        long = matrix.reset_index(names="var_1").melt(
            id_vars="var_1", var_name="var_2", value_name="correlation"
        ).replace([np.inf, -np.inf], np.nan).dropna()
        if long.empty:
            return spec(None, frame, columns,
                        warnings=["All correlations are undefined (constant columns or insufficient data)."])
        chart = alt.Chart(long).mark_rect(stroke="white", strokeWidth=1).encode(
            x=alt.X("var_1:N", title="", sort=columns, axis=alt.Axis(labelAngle=-35)),
            y=alt.Y("var_2:N", title="", sort=columns),
            color=alt.Color("correlation:Q",
                            scale=alt.Scale(scheme="redblue", domain=[-1, 1]),
                            legend=alt.Legend(title="Pearson r")),
            tooltip=[alt.Tooltip("var_1:N", title="Variable 1"),
                     alt.Tooltip("var_2:N", title="Variable 2"),
                     alt.Tooltip("correlation:Q", format=".4f")],
        ).properties(width="container", height=380)
        return spec(
            chart, long, columns,
            notes=["Pearson correlation measures linear association only. Undefined pairs are left blank.",
                   "Computed on pairwise-complete observations in the current cleaned dataset."],
            warnings=["Correlation does not imply causation."],
        )

    # ---- Single-column distribution plots ----
    if plot_type in (PLOT_HISTOGRAM, PLOT_DISTRIBUTION, PLOT_BOX):
        column = y_col if plot_type == PLOT_BOX else x_col
        column_label = y_label if plot_type == PLOT_BOX else x_label
        if not column or column not in frame.columns:
            return spec(None, frame, [], warnings=["Select a numeric measurement column."])
        values = coerce_numeric(frame[column]).values
        has_group = bool(group_col and group_col in frame.columns and group_col != column)
        if plot_type == PLOT_BOX:
            labels = (frame[group_col].astype("string").fillna("(missing)").to_numpy()
                      if has_group else np.full(len(frame), "(all rows)", dtype=object))
            data = pd.DataFrame({"group": labels, "value": values})
            data = data.replace([np.inf, -np.inf], np.nan).dropna()
            if data.empty:
                return spec(None, data, [column], warnings=[f"No finite values in '{column}'."])
            valid_count = len(data)
            data = data.head(MAX_CHART_ROWS)
            chart = alt.Chart(data).mark_boxplot(extent="min-max", size=40).encode(
                x=alt.X("group:N", title=group_col or "", axis=alt.Axis(labelAngle=-30)),
                y=alt.Y("value:Q", title=column_label, scale=alt.Scale(zero=False)),
                color=alt.Color("group:N", legend=None) if has_group else alt.value("#2b6cb0"),
                tooltip=[alt.Tooltip("group:N", title="Group"), alt.Tooltip("value:Q", title=column_label)],
            ).properties(width="container", height=340)
            return spec(
                chart, data, [column] + ([group_col] if has_group else []),
                notes=[f"{valid_count} valid row(s); {len(frame) - valid_count} row(s) excluded for this chart.",
                       "Boxes show median, quartiles and min-max whiskers; outliers are flagged, not removed.",
                       "The Y axis is not forced to start at zero so that spread remains visible."],
                warnings=["Groups with very few observations give unstable quartiles."]
                + ([f"Only the first {MAX_CHART_ROWS:,} valid rows are plotted."]
                   if valid_count > MAX_CHART_ROWS else []),
            )
        data = pd.DataFrame({"value": values}).replace([np.inf, -np.inf], np.nan).dropna()
        valid_count = len(data)
        data = data.head(MAX_CHART_ROWS)
        if data.empty:
            return spec(None, data, [column], warnings=[f"No finite values in '{column}'."])
        if plot_type == PLOT_HISTOGRAM:
            chart = alt.Chart(data).mark_bar(color="#2b6cb0", opacity=0.85).encode(
                x=alt.X("value:Q", bin=alt.Bin(maxbins=bins), title=column_label),
                y=alt.Y("count():Q", title="Count"),
                tooltip=[alt.Tooltip("count():Q", title="Count")],
            )
            note = f"Histogram uses up to {bins} automatic bins; bin choice affects apparent shape."
        else:
            chart = alt.Chart(data).transform_density(
                "value", as_=["value", "density"]
            ).mark_area(color="#2b6cb0", opacity=0.5).encode(
                x=alt.X("value:Q", title=column_label),
                y=alt.Y("density:Q", title="Estimated density"),
            )
            note = "Kernel density is a smoothing estimate, not a measured probability; bandwidth affects its shape."
        return spec(
            chart.properties(width="container", height=340), data, [column],
            notes=[f"{valid_count} valid row(s); {len(frame) - valid_count} row(s) excluded for this chart.", note],
            warnings=(["A constant column produces a single spike and is not informative."]
                      if np.ptp(data["value"].to_numpy()) == 0 else [])
            + ([f"Only the first {MAX_CHART_ROWS:,} valid rows are plotted."]
               if valid_count > MAX_CHART_ROWS else []),
        )

    # ---- Grouped comparison (mean per category) ----
    if plot_type == PLOT_GROUPED_BAR:
        if not y_col or not group_col or y_col not in frame.columns or group_col not in frame.columns:
            return spec(None, frame, [],
                        warnings=["A grouped comparison needs both a Y measurement and a group/category column."])
        data = pd.DataFrame({
            "group": frame[group_col].astype("string").fillna("(missing)").to_numpy(),
            "value": coerce_numeric(frame[y_col]).values,
        }).replace([np.inf, -np.inf], np.nan).dropna()
        if data.empty:
            return spec(None, data, [y_col], warnings=[f"No finite values in '{y_col}'."])
        summary = data.groupby("group", dropna=False)["value"].agg(["mean", "std", "count"]).reset_index()
        chart = alt.Chart(summary).mark_bar(color="#2b6cb0").encode(
            x=alt.X("group:N", title=group_col, axis=alt.Axis(labelAngle=-30)),
            y=alt.Y("mean:Q", title=f"Mean of {y_col}", scale=alt.Scale(zero=True)),
            tooltip=[alt.Tooltip("group:N", title=group_col),
                     alt.Tooltip("mean:Q", format=".6g"),
                     alt.Tooltip("std:Q", format=".6g"),
                     alt.Tooltip("count:Q", title="n")],
        ).properties(width="container", height=340)
        return spec(
            chart, summary, [y_col, group_col],
            warnings=["Bar height is an arithmetic mean, not a measurement. Error bars are NOT shown "
                      "because no uncertainty column was supplied; do not read differences as significant."],
            notes=["The Y axis starts at zero because bar length encodes magnitude."],
        )

    # ---- Two-column plots: scatter, line, time series, error bars ----
    x_name = (time_col or x_col) if plot_type == PLOT_TIME_SERIES else x_col
    y_name = y_col
    if not x_name or not y_name:
        return spec(None, frame, [], warnings=["Select both an X and a Y column for this plot."])
    if plot_type == PLOT_TIME_SERIES:
        time_unit = config.get("unit_x") if x_name == x_col else config.get("unit_time")
        x_label = _axis_label(x_name, time_unit)
    missing = [c for c in (x_name, y_name, unc_col if plot_type == PLOT_ERRORBAR else None)
               if c and c not in frame.columns]
    if missing:
        return spec(None, frame, [], warnings=[f"Missing column(s): {', '.join(missing)}."])
    if plot_type == PLOT_ERRORBAR and not unc_col:
        return spec(None, frame, [],
                    warnings=["Select an uncertainty column to draw error bars. LabLens will not invent uncertainties."])

    has_unc = bool(plot_type == PLOT_ERRORBAR and unc_col and unc_col in frame.columns)
    has_group = bool(group_col and group_col in frame.columns)
    is_temporal = (plot_type == PLOT_TIME_SERIES
                   and not pd.api.types.is_numeric_dtype(frame[x_name]))
    try:
        x_values = (pd.to_datetime(frame[x_name], errors="coerce", format="mixed").to_numpy()
                    if is_temporal else coerce_numeric(frame[x_name]).values)
    except (ValueError, TypeError) as exc:
        return spec(None, frame, [], warnings=[f"Could not interpret '{x_name}' as a time axis: {exc}"])
    data = pd.DataFrame({
        "x": x_values,
        "y": coerce_numeric(frame[y_name]).values,
    })
    finite = np.array(
        data["x"].notna().to_numpy() if is_temporal
        else np.isfinite(data["x"].to_numpy(dtype=float, na_value=np.nan)),
        dtype=bool, copy=True,
    )
    finite &= np.isfinite(data["y"].to_numpy(dtype=float, na_value=np.nan))
    if has_group:
        data["group"] = frame[group_col].astype("string").fillna("(missing)").to_numpy()
    if has_unc:
        data["err"] = coerce_numeric(frame[unc_col]).values
        err = data["err"].to_numpy(dtype=float, na_value=np.nan)
        finite &= np.isfinite(err) & (err >= 0)
    valid_count = int(finite.sum())
    excluded_count = len(frame) - valid_count
    data = data[finite].head(MAX_CHART_ROWS).reset_index(drop=True)
    if data.empty:
        return spec(None, data, [x_name, y_name],
                    warnings=["No complete finite rows remain for the selected columns (and uncertainties, if any)."])

    warnings: list[str] = []
    notes: list[str] = [f"{valid_count} valid row(s); {excluded_count} row(s) excluded for this chart."]
    if plot_type in (PLOT_LINE, PLOT_TIME_SERIES):
        original = data["x"].to_numpy()
        data = data.sort_values("x", kind="stable").reset_index(drop=True)
        if len(original) > 1 and not np.all(original[:-1] <= original[1:]):
            warnings.append("X was not sorted in the source data; connecting points in sorted order "
                            "can hide or create apparent trends.")
        if data["x"].duplicated().any():
            warnings.append("Repeated X values are connected as one series; consider grouping instead.")

    x_encoding = (alt.X("x:T", title=x_label) if is_temporal
                  else alt.X("x:Q", title=x_label, scale=alt.Scale(zero=False)))
    y_encoding = alt.Y("y:Q", title=y_label, scale=alt.Scale(zero=False))
    color = (alt.Color("group:N", legend=alt.Legend(title=group_col))
             if has_group else alt.value("#2b6cb0"))
    tooltip = [alt.Tooltip("x:T" if is_temporal else "x:Q", title=x_label),
               alt.Tooltip("y:Q", title=y_label, format=".6g")]
    if has_unc:
        tooltip.append(alt.Tooltip("err:Q", title=unc_col, format=".6g"))
    if has_group:
        tooltip.append(alt.Tooltip("group:N", title=group_col))

    layers = []
    if plot_type == PLOT_ERRORBAR:
        data["lo"] = data["y"] - data["err"]
        data["hi"] = data["y"] + data["err"]
        layers.append(alt.Chart(data).mark_errorbar(color="#666").encode(
            x=alt.X("x:Q", title=x_label, scale=alt.Scale(zero=False)),
            y=alt.Y("lo:Q", title=y_label), y2="hi:Q",
        ))
        layers.append(alt.Chart(data).mark_circle(size=55, color="#2b6cb0").encode(
            x=alt.X("x:Q", title=x_label, scale=alt.Scale(zero=False)),
            y=y_encoding, tooltip=tooltip,
        ))
        notes.append(f"Error bars are ±1 value from '{unc_col}' exactly as supplied. Verify whether "
                     "the source reports standard deviation, standard error, or instrument accuracy — "
                     "they are not interchangeable.")
    elif plot_type in (PLOT_LINE, PLOT_TIME_SERIES):
        encode_args = dict(x=x_encoding, y=y_encoding, color=color, tooltip=tooltip)
        if has_group:
            encode_args["detail"] = "group:N"
        layers.append(alt.Chart(data).mark_line(point=True, opacity=0.85).encode(**encode_args))
    else:
        layers.append(alt.Chart(data).mark_circle(size=60, opacity=0.75).encode(
            x=x_encoding, y=y_encoding, color=color, tooltip=tooltip,
        ))

    if (plot_type == PLOT_SCATTER and config.get("show_fit", True)
            and fit_result is not None and getattr(fit_result, "success", False)):
        from fitting_core import predict_with_flags
        prediction = predict_with_flags(fit_result, fit_result.x_fit)
        if prediction.get("valid"):
            fitted = pd.DataFrame({
                "x": np.asarray(fit_result.x_fit, dtype=float),
                "y": np.asarray(prediction["predicted"], dtype=float),
            }).replace([np.inf, -np.inf], np.nan).dropna().sort_values("x")
            layers.append(alt.Chart(fitted).mark_line(color="#b22222", strokeWidth=2).encode(
                x=alt.X("x:Q", title=x_label, scale=alt.Scale(zero=False)),
                y=alt.Y("y:Q", title=y_label, scale=alt.Scale(zero=False)),
            ))
            notes.append(f"Red line: fitted {fit_result.label}. It is a model, not measured data.")

    if secondary_cols:
        warnings.append("A secondary Y axis was requested but is intentionally not overlaid: dual axes "
                        "can imply relationships that depend entirely on scale choices. Plot each Y separately.")
    if plot_type in (PLOT_SCATTER, PLOT_LINE, PLOT_ERRORBAR):
        notes.append("Axes are not forced to start at zero; the displayed range is chosen to show the data.")
    if valid_count > MAX_CHART_ROWS:
        warnings.append(f"Only the first {MAX_CHART_ROWS:,} rows are plotted; filter or aggregate the data first.")

    chart = layers[0] if len(layers) == 1 else alt.layer(*layers)
    return spec(
        chart.properties(width="container", height=360), data,
        [x_name, y_name] + ([unc_col] if has_unc else []),
        warnings=warnings, notes=notes,
    )


def render_png(plot_type: str, frame: pd.DataFrame, config: dict) -> bytes:
    """Matplotlib fallback for PNG export (no browser or CDN required)."""
    spec = build_chart(plot_type, frame, config)
    fig, ax = plt.subplots(figsize=(8, 4.8), dpi=150)
    data = spec.frame
    x_col, y_col = config.get("x"), config.get("y")
    time_col = config.get("time")
    x_label = _axis_label(x_col, config.get("unit_x"))
    y_label = _axis_label(y_col, config.get("unit_y"))
    extra: list[str] = []

    try:
        if not spec.valid:
            ax.text(0.5, 0.5, spec.reason or "Not available", ha="center", va="center", wrap=True)
            ax.set_axis_off()
        elif plot_type in (PLOT_HISTOGRAM, PLOT_DISTRIBUTION):
            values = data["value"].to_numpy(dtype=float)
            ax.hist(values, bins=min(max(int(config.get("bins", 30) or 30), 5), 100),
                    color="#2b6cb0", alpha=0.85, density=plot_type == PLOT_DISTRIBUTION)
            ax.set_xlabel(x_label or "value")
            ax.set_ylabel("Density" if plot_type == PLOT_DISTRIBUTION else "Count")
        elif plot_type == PLOT_HEATMAP:
            from statistics_core import correlation_matrix
            columns = [c for c in (config.get("numeric_columns") or [x_col, y_col]) if c]
            matrix = correlation_matrix(frame, columns, method="pearson")
            image = ax.imshow(matrix.to_numpy(dtype=float), vmin=-1, vmax=1, cmap="RdBu_r")
            ax.set_xticks(range(len(matrix)), matrix.columns, rotation=40, ha="right")
            ax.set_yticks(range(len(matrix)), matrix.index)
            for i in range(len(matrix)):
                for j in range(len(matrix)):
                    value = matrix.iloc[i, j]
                    if np.isfinite(value):
                        ax.text(j, i, f"{value:.2f}", ha="center", va="center", fontsize=8)
            fig.colorbar(image, ax=ax, label="Pearson r")
        elif plot_type == PLOT_BOX:
            labels = [str(item) for item in data["group"].unique()]
            ax.boxplot([data.loc[data["group"].astype(str) == label, "value"].to_numpy()
                        for label in labels], tick_labels=labels)
            ax.set_ylabel(y_label or x_label)
        elif plot_type == PLOT_RESIDUALS:
            ax.scatter(data["x"], data["residual"], s=26, alpha=0.8)
            ax.axhline(0, color="#b22222", linestyle="--")
            ax.set_xlabel(x_col or "X")
            ax.set_ylabel("Residual (observed - fitted)")
        elif plot_type == PLOT_GROUPED_BAR:
            ax.bar(data["group"].astype(str), data["mean"], color="#2b6cb0")
            ax.set_ylabel(f"Mean of {y_col}")
            extra.append("Bars show means; no uncertainty was inferred.")
        else:
            style = "-" if plot_type in (PLOT_LINE, PLOT_TIME_SERIES) else "o"
            if "group" in data.columns:
                for label, group_data in data.groupby("group", sort=False, dropna=False):
                    ax.plot(group_data["x"], group_data["y"], style, markersize=5, alpha=0.85,
                            label=str(label))
                ax.legend(title=config.get("group"))
            else:
                ax.plot(data["x"], data["y"], style, markersize=5, alpha=0.85)
            if plot_type == PLOT_ERRORBAR and {"lo", "hi"}.issubset(data.columns):
                ax.errorbar(data["x"], data["y"],
                            yerr=[data["y"] - data["lo"], data["hi"] - data["y"]],
                            fmt="none", ecolor="#777", capsize=3)
            if plot_type == PLOT_SCATTER and config.get("show_fit", True):
                fit_result = config.get("fit_result")
                if fit_result is not None and getattr(fit_result, "success", False):
                    from fitting_core import predict_with_flags
                    prediction = predict_with_flags(fit_result, fit_result.x_fit)
                    if prediction.get("valid"):
                        fitted = pd.DataFrame({"x": fit_result.x_fit, "y": prediction["predicted"]})
                        fitted = fitted.replace([np.inf, -np.inf], np.nan).dropna().sort_values("x")
                        ax.plot(fitted["x"], fitted["y"], color="#b22222", label="Fitted model")
                        ax.legend()
            if plot_type == PLOT_TIME_SERIES:
                time_name = time_col or x_col
                time_unit = config.get("unit_x") if time_name == x_col else config.get("unit_time")
                ax.set_xlabel(_axis_label(time_name, time_unit))
            else:
                ax.set_xlabel(x_label)
            ax.set_ylabel(y_label)
        ax.set_title(PLOT_TYPES.get(plot_type, plot_type))
        if spec.notes or spec.warnings or extra:
            text = " | ".join([*spec.notes, *spec.warnings, *extra])[:600]
            fig.text(0.01, 0.01, text, fontsize=6, color="#444", wrap=True)
        fig.tight_layout(rect=(0, 0.06, 1, 1))
        buffer = io.BytesIO()
        fig.savefig(buffer, format="png", bbox_inches="tight")
        return buffer.getvalue()
    finally:
        plt.close(fig)
